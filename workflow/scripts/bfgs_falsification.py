"""BFGS most-likely-failure falsification for the HolosMulti environment."""

import numpy as np
from fuzzing import Disturbance


class NominalTrajectoryDistribution:
    """Bundles disturbance distribution and trajectory depth for likelihood computation.

    Args:
        D (DisturbanceDistribution): disturbance distribution for each timestep.
        d (int): trajectory depth (number of env.step calls).
    """

    def __init__(self, D, d):
        self.D = D
        self.d = d

    def logpdf(self, disturbances):
        """Log-probability of a disturbance sequence under the nominal distribution.

        Args:
            disturbances (list[Disturbance]): one Disturbance per timestep.

        Returns:
            float: joint log-probability across all timesteps.
        """
        lp = 0.0
        for x in disturbances:
            if self.D.Do.dim > 0:
                lp += self.D.Do.logpdf(x.xo)
            if self.D.Da.dim > 0:
                lp += self.D.Da.logpdf(x.xa)
            if self.D.Ds.dim > 0:
                lp += self.D.Ds.logpdf(x.xs)
        return lp


def _unpack_xo(values, do):
    """Convert a flat array slice into an xo dict for the HolosMulti env.

    Args:
        values (numpy array): flat array of do.dim values.
        do (Do): observation disturbance distribution.

    Returns:
        dict: keys "p" (float) and "drum_angles" (array of 8).
    """
    xo = {"p": 0.0, "drum_angles": np.zeros(8)}
    idx = 0
    if do.power_dd.std() > 0:
        xo["p"] = values[idx]
        idx += 1
    if do.drum_dd.std() > 0:
        xo["drum_angles"] = values[idx:idx + 8]
    return xo


def _unpack_xs(values, ds):
    """Convert a flat array slice into a 12-element state disturbance array.

    Args:
        values (numpy array): flat array of ds.dim values.
        ds (Ds): state disturbance distribution.

    Returns:
        numpy array: 12-element array in state ordering [n_r, c1-c6, Tf, Tm, Tc, xe, i].
    """
    xs = np.zeros(12)
    idx = 0
    if ds.nr_dd.std() > 0:
        xs[0] = values[idx]; idx += 1
    if ds.precursor_dd.std() > 0:
        xs[1:7] = values[idx:idx + 6]; idx += 6
    if ds.Tf_dd.std() > 0:
        xs[7] = values[idx]; idx += 1
    if ds.Tm_dd.std() > 0:
        xs[8] = values[idx]; idx += 1
    if ds.Tc_dd.std() > 0:
        xs[9] = values[idx]; idx += 1
    if ds.xe_dd.std() > 0:
        xs[10] = values[idx]; idx += 1
    if ds.i_dd.std() > 0:
        xs[11] = values[idx]; idx += 1
    return xs

# Generate by Claude Opus 4.6
def extract(x_vec, dd, depth):
    """Unpack a flat optimization vector into reset xo and a disturbance sequence.

    Args:
        x_vec (numpy array): flat optimization vector.
        dd (DisturbanceDistribution): defines active channels and their dimensions.
        depth (int): number of env.step calls (len of disturbance list).

    Returns:
        tuple: (reset_xo dict, list[Disturbance] of length depth).
    """
    do_dim = dd.Do.dim
    da_dim = dd.Da.dim
    ds_dim = dd.Ds.dim

    idx = 0
    reset_xo = _unpack_xo(x_vec[idx:idx + do_dim], dd.Do) if do_dim > 0 else {"p": 0.0, "drum_angles": np.zeros(8)}
    idx += do_dim

    disturbances = []
    for _ in range(depth):
        xo = _unpack_xo(x_vec[idx:idx + do_dim], dd.Do) if do_dim > 0 else {"p": 0.0, "drum_angles": np.zeros(8)}
        idx += do_dim

        xa = x_vec[idx:idx + da_dim].copy() if da_dim > 0 else np.zeros(8)
        idx += da_dim

        xs = _unpack_xs(x_vec[idx:idx + ds_dim], dd.Ds) if ds_dim > 0 else np.zeros(12)
        idx += ds_dim

        disturbances.append(Disturbance(xo, xa, xs))

    return reset_xo, disturbances

# Generated by Claude Opus 4.6
def rollout_with_disturbances(model, env, reset_xo, disturbances):
    """Run a deterministic rollout with pre-specified disturbances.

    Args:
        model (sb3.PPO): trained policy.
        env (HolosMulti): environment instance (training=False, max_failed_drums=0).
        reset_xo (dict): observation disturbance for the initial reset step.
        disturbances (list[Disturbance]): one per env.step call.

    Returns:
        tuple: (actual_power, desired_power) as numpy arrays of length len(history).
    """
    obs, _ = env.reset(options={"xo": reset_xo})
    for x in disturbances:
        action, _ = model.predict(obs, deterministic=True)
        obs, _, terminated, truncated, _ = env.step(action, x)
        if terminated or truncated:
            break
    actual_power = np.array([h[11] for h in env.history])
    desired_power = np.array([h[2] for h in env.history])
    return actual_power, desired_power


# Generated by Claude Opus 4.6
def check_spec(actual, desired):
    """Check if power trajectory stays within 3% relative of desired.

    Args:
        actual (numpy array): actual power at each timestep.
        desired (numpy array): desired power at each timestep.

    Returns:
        bool: True if spec satisfied at all timesteps.
    """
    return (np.abs(actual - desired) / desired < 0.03).all()

# Generate by Claude Opus 4.6
def robustness(actual, desired, smoothness=0.0):
    """STL robustness for the 3% relative power spec.

    Positive means satisfying, negative means violating.

    Args:
        actual (numpy array): actual power at each timestep.
        desired (numpy array): desired power at each timestep.
        smoothness (float): log-sum-exp smoothing parameter. 0 for exact min.

    Returns:
        float: robustness value.
    """
    margins = 0.03 - np.abs(actual - desired) / desired
    if smoothness > 0:
        return -smoothness * np.log(np.sum(np.exp(-margins / smoothness)))
    return np.min(margins)


# Claude Opus 4.6 — fixes x0 init crash when sigma_drum=0 (dim=1 but old code packed 9 values)
def _sample_do_flat(do):
    """Sample a flat array of do.dim values for active channels.

    Args:
        do (Do): observation disturbance distribution.

    Returns:
        numpy array: flat array of do.dim values.
    """
    parts = []
    if do.power_dd.std() > 0:
        parts.append([do.power_dd.rvs()])
    if do.drum_dd.std() > 0:
        parts.append(do.drum_dd.rvs(size=8))
    return np.concatenate(parts) if parts else np.array([])


PENALTY = 1e6


def likelihood_objective(x_vec, model, env, nominal_dist, smoothness=0.0):
    """Two-phase objective for BFGS most-likely-failure search.

    If the trajectory violates the spec, maximizes failure likelihood.
    Otherwise, pushes toward the failure boundary via robustness.

    Args:
        x_vec (numpy array): flat optimization vector.
        model: trained policy with .predict().
        env: HolosMulti environment instance.
        nominal_dist (NominalTrajectoryDistribution): for likelihood computation.
        smoothness (float): robustness smoothing parameter.

    Returns:
        float: objective value for scipy.optimize.minimize.
    """
    reset_xo, disturbances = extract(x_vec, nominal_dist.D, nominal_dist.d)
    try:
        actual, desired = rollout_with_disturbances(model, env, reset_xo, disturbances)
    except Exception:
        return PENALTY

    if not check_spec(actual, desired):
        logp = nominal_dist.logpdf(disturbances)
        return -logp / nominal_dist.d
    else:
        return robustness(actual, desired, smoothness)


def make_objective(model, env, nominal_dist, smoothness=0.0):
    """Curry likelihood_objective into f(x_vec) -> scalar for scipy.

    Args:
        model: trained policy.
        env: HolosMulti environment instance.
        nominal_dist (NominalTrajectoryDistribution): for likelihood computation.
        smoothness (float): robustness smoothing parameter.

    Returns:
        callable: f(x_vec) -> float.
    """
    def objective(x_vec):
        return likelihood_objective(x_vec, model, env, nominal_dist, smoothness)
    return objective


# Claude Opus 4.6 — parallelized restarts across CPU cores to speed up optimization.
# Each worker gets its own model/env to avoid shared-state issues.
def _run_one_restart(args):
    """Worker function for a single BFGS restart. Runs in its own process.

    Args:
        args (tuple): (restart_index, random_seed, config dict with scalar params).

    Returns:
        dict: result with 'failure', 'actual', 'desired', 'obj', 'converged', 'max_dev'.
    """
    i, seed, cfg = args
    from scipy.optimize import minimize
    import stable_baselines3 as sb3
    from env import HolosMulti
    from profiles import get_profile
    from fuzzing import DisturbanceDistribution, Do, Da, Ds

    np.random.seed(seed)
    model = sb3.PPO.load(cfg["model_path"], device="cpu")
    _, testing_kwargs = get_profile("test")
    testing_kwargs["max_failed_drums"] = 0
    env = HolosMulti(**testing_kwargs)
    depth = env.episode_length - 1

    dd = DisturbanceDistribution(
        Do=Do(sigma_p=cfg["sigma_p"], sigma_drum=cfg["sigma_drum"]),
        Da=Da(sigma_dtheta=0), Ds=Ds())
    nominal_dist = NominalTrajectoryDistribution(dd, depth)
    obj = make_objective(model, env, nominal_dist, smoothness=cfg["smoothness"])

    vec_len = dd.Do.dim + depth * dd.dim
    x0 = np.zeros(vec_len)
    idx = 0
    do_dim = dd.Do.dim
    x0[idx:idx + do_dim] = _sample_do_flat(dd.Do)
    idx += do_dim
    for _ in range(depth):
        x0[idx:idx + do_dim] = _sample_do_flat(dd.Do)
        idx += do_dim

    n_eval = [0]
    def callback(xk):
        n_eval[0] += 1
        print(f"  [{i+1}] iteration {n_eval[0]}", flush=True)

    result = minimize(obj, x0, method='L-BFGS-B',
                      options={'maxiter': cfg["max_iter"]},
                      callback=callback)
    reset_xo, dist_opt = extract(result.x, dd, depth)
    actual, desired = rollout_with_disturbances(model, env, reset_xo, dist_opt)
    is_failure = not check_spec(actual, desired)
    max_dev = float(np.max(np.abs(actual - desired) / desired))

    print(f"[{i+1}/{cfg['n_opt']}] converged={result.success}, failure={is_failure}, "
          f"obj={result.fun:.4f}, max_dev={max_dev:.4f}", flush=True)

    return {"failure": is_failure, "actual": actual, "desired": desired,
            "obj": float(result.fun), "converged": result.success, "max_dev": max_dev,
            "x_vec": result.x, "seed": seed, "n_iterations": n_eval[0]}


