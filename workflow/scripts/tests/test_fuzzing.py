# --- Do.dim / Do.logpdf ---
# Tests below were generated by Claude Opus 4.6.

def test_do_dim_both_active():
    assert Do(sigma_p=0.01, sigma_drum=0.005).dim == 9

def test_do_dim_power_only():
    assert Do(sigma_p=0.01, sigma_drum=0).dim == 1

def test_do_dim_drums_only():
    assert Do(sigma_p=0, sigma_drum=0.005).dim == 8

def test_do_dim_both_off():
    assert Do(sigma_p=0, sigma_drum=0).dim == 0

def test_do_logpdf_matches_scipy():
    """Verify logpdf against direct scipy.stats.norm computation."""
    from scipy.stats import norm
    sigma_p, sigma_drum = 0.01, 0.005
    do = Do(sigma_p=sigma_p, sigma_drum=sigma_drum)
    xo = {"p": 0.002, "drum_angles": np.full(8, 0.001)}
    expected = norm(0, sigma_p).logpdf(0.002) + np.sum(norm(0, sigma_drum).logpdf(np.full(8, 0.001)))
    assert do.logpdf(xo) == pytest.approx(expected)

def test_do_logpdf_zero_sigma_ignored():
    """Channels with sigma=0 contribute nothing to logpdf."""
    do = Do(sigma_p=0.01, sigma_drum=0)
    xo = {"p": 0.0, "drum_angles": np.ones(8) * 999}
    from scipy.stats import norm
    assert do.logpdf(xo) == pytest.approx(norm(0, 0.01).logpdf(0.0))


# --- Da.dim / Da.logpdf ---

def test_da_dim_active():
    assert Da(sigma_dtheta=0.001).dim == 8

def test_da_dim_off():
    assert Da(sigma_dtheta=0).dim == 0

def test_da_logpdf_matches_scipy():
    from scipy.stats import norm
    sigma = 0.001
    da = Da(sigma_dtheta=sigma)
    xa = np.full(8, 0.0005)
    expected = np.sum(norm(0, sigma).logpdf(xa))
    assert da.logpdf(xa) == pytest.approx(expected)

def test_da_logpdf_zero_sigma_returns_zero():
    assert Da(sigma_dtheta=0).logpdf(np.ones(8)) == 0.0


# --- Ds.dim / Ds.logpdf ---

def test_ds_dim_all_off():
    assert Ds().dim == 0

def test_ds_dim_single_channel():
    assert Ds(sigma_Tf=0.1).dim == 1

def test_ds_dim_precursors_count_as_six():
    assert Ds(sigma_precursors=0.01).dim == 6

def test_ds_dim_all_active():
    ds = Ds(sigma_nr=0.1, sigma_precursors=0.1, sigma_Tf=0.1,
            sigma_Tm=0.1, sigma_Tc=0.1, sigma_xe=0.1, sigma_i=0.1)
    assert ds.dim == 12

def test_ds_logpdf_matches_scipy():
    from scipy.stats import norm
    ds = Ds(sigma_Tf=0.1, sigma_Tm=0.2)
    xs = np.zeros(12)
    xs[7] = 0.05  # Tf
    xs[8] = 0.1   # Tm
    expected = norm(0, 0.1).logpdf(0.05) + norm(0, 0.2).logpdf(0.1)
    assert ds.logpdf(xs) == pytest.approx(expected)

def test_ds_logpdf_all_off_returns_zero():
    assert Ds().logpdf(np.ones(12)) == 0.0


