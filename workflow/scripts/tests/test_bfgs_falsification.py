# --- extract round-trip ---

def test_extract_do_only_recovers_values():
    """Pack known values into a vector, extract, verify they come back."""
    dd = DisturbanceDistribution(Do=Do(0.01, 0.005), Da=Da(0), Ds=Ds())
    depth = 3
    vec_len = dd.Do.dim + depth * dd.dim  # reset_xo + 3 steps
    x_vec = np.arange(vec_len, dtype=float)

    reset_xo, disturbances = extract(x_vec, dd, depth)

    assert reset_xo["p"] == 0.0
    np.testing.assert_array_equal(reset_xo["drum_angles"], np.arange(1, 9))
    assert len(disturbances) == depth
    # first step starts at index 9
    assert disturbances[0].xo["p"] == 9.0
    np.testing.assert_array_equal(disturbances[0].xo["drum_angles"], np.arange(10, 18))


def test_extract_power_only_skips_drums():
    """With sigma_drum=0, drum_angles should be zeros regardless of vector content."""
