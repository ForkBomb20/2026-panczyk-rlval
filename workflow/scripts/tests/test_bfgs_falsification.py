# --- NominalTrajectoryDistribution.logpdf ---

def test_nominal_dist_logpdf_sums_over_steps():
    """logpdf should equal the sum of per-step Do logpdfs."""
    do = Do(sigma_p=0.01, sigma_drum=0.005)
    dd = DisturbanceDistribution(Do=do, Da=Da(0), Ds=Ds())
    depth = 3
    nominal = NominalTrajectoryDistribution(dd, depth)

    xo = {"p": 0.001, "drum_angles": np.full(8, 0.002)}
    disturbances = [Disturbance(xo, np.zeros(8), np.zeros(12)) for _ in range(depth)]

    expected = depth * do.logpdf(xo)
    assert nominal.logpdf(disturbances) == pytest.approx(expected)


# --- check_spec ---

def test_check_spec_passing():
    desired = np.array([1.0, 0.8, 0.6])
    actual = desired * 1.01  # 1% off
    assert check_spec(actual, desired)


def test_check_spec_failing():
    desired = np.array([1.0, 0.8, 0.6])
    actual = desired.copy()
    actual[1] = 0.8 * 1.05  # 5% off at step 1
    assert not check_spec(actual, desired)


def test_check_spec_boundary():
    """Exactly 3% deviation should fail (strict inequality)."""
    desired = np.array([1.0])
    actual = np.array([1.03])
    assert not check_spec(actual, desired)


# --- robustness ---

def test_robustness_positive_when_in_spec():
    desired = np.array([1.0, 0.8])
    actual = desired * 1.01  # 1% off, well within 3%
    assert robustness(actual, desired) > 0


def test_robustness_negative_when_out_of_spec():
    desired = np.array([1.0, 0.8])
    actual = desired * 1.05  # 5% off
    assert robustness(actual, desired) < 0


def test_robustness_exact_value():
    """With 1% deviation, margin should be 0.03 - 0.01 = 0.02."""
    desired = np.array([1.0])
    actual = np.array([1.01])
    assert robustness(actual, desired) == pytest.approx(0.02)


def test_robustness_smooth_approximates_exact():
    desired = np.array([1.0, 0.8, 0.6])
    actual = desired * 1.01
    exact = robustness(actual, desired, smoothness=0.0)
    smooth = robustness(actual, desired, smoothness=0.001)
    assert smooth == pytest.approx(exact, abs=2e-3)
