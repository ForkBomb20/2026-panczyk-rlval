def test_rollout_deterministic(model_and_env):
    """Same disturbances produce identical trajectories."""
    model, env = model_and_env
    dd = DisturbanceDistribution(Do=Do(0.005, 0.005), Da=Da(0), Ds=Ds())
    depth = env.episode_length - 1

    np.random.seed(42)
    reset_xo = dd.Do.sample()
    disturbances = [Disturbance(dd.Do.sample(), np.zeros(8), np.zeros(12)) for _ in range(depth)]

    actual1, desired1 = rollout_with_disturbances(model, env, reset_xo, disturbances)
    actual2, desired2 = rollout_with_disturbances(model, env, reset_xo, disturbances)

    np.testing.assert_array_equal(actual1, actual2)
    np.testing.assert_array_equal(desired1, desired2)


# --- likelihood_objective ---

def _make_nominal_dist(depth):
    """Helper to build a NominalTrajectoryDistribution for testing."""
    dd = DisturbanceDistribution(Do=Do(0.01, 0.005), Da=Da(0), Ds=Ds())
    return NominalTrajectoryDistribution(dd, depth), dd


def test_objective_returns_robustness_when_in_spec():
    """When spec is satisfied, objective should equal robustness."""
    depth = 3
    nominal, dd = _make_nominal_dist(depth)
    x_vec = np.zeros(dd.Do.dim + depth * dd.dim)

    desired = np.array([1.0, 0.99, 0.98, 0.97])
    actual = desired * 1.001  # well within 3%

    with patch("bfgs_falsification.rollout_with_disturbances", return_value=(actual, desired)):
        val = likelihood_objective(x_vec, None, None, nominal, smoothness=0.1)
    expected = robustness(actual, desired, smoothness=0.1)
    assert val == pytest.approx(expected)


def test_objective_returns_neg_logpdf_when_failing():
    """When spec is violated, objective should be -logpdf/depth."""
    depth = 3
    nominal, dd = _make_nominal_dist(depth)
    x_vec = np.zeros(dd.Do.dim + depth * dd.dim)

    desired = np.array([1.0, 0.99, 0.98, 0.97])
    actual = desired * 1.10  # 10% off, fails spec

    with patch("bfgs_falsification.rollout_with_disturbances", return_value=(actual, desired)):
        val = likelihood_objective(x_vec, None, None, nominal, smoothness=0.1)
    _, disturbances = extract(x_vec, dd, depth)
    expected = -nominal.logpdf(disturbances) / depth
    assert val == pytest.approx(expected)


def test_objective_returns_penalty_on_exception():
    """Numerical blowup should return PENALTY, not crash."""
    depth = 3
    nominal, dd = _make_nominal_dist(depth)
    x_vec = np.zeros(dd.Do.dim + depth * dd.dim)

    with patch("bfgs_falsification.rollout_with_disturbances", side_effect=RuntimeError("solve_ivp failed")):
        val = likelihood_objective(x_vec, None, None, nominal)
    assert val == PENALTY


def test_make_objective_is_callable():
    nominal, dd = _make_nominal_dist(3)
    obj = make_objective(None, None, nominal, smoothness=0.1)
    assert callable(obj)
